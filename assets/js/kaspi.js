// Global navigation
function switchView(viewId) {
    // Hide all views
    document.querySelectorAll('.view-container').forEach(el => {
        el.classList.remove('active-view');
    });
    // Show target
    document.getElementById(viewId).classList.add('active-view');
    window.scrollTo(0, 0);

    // Update bottom nav
    if (['view-home', 'view-qr', 'view-messages', 'view-services'].includes(viewId)) {
        document.querySelectorAll('.nav-item').forEach(el => el.classList.remove('active'));
        if (viewId === 'view-home') document.getElementById('nav-home').classList.add('active');
        if (viewId === 'view-qr') document.getElementById('nav-qr').classList.add('active');
        if (viewId === 'view-messages') document.getElementById('nav-messages').classList.add('active');
        if (viewId === 'view-services') document.getElementById('nav-services').classList.add('active');
    }
}

// QR Camera Simulation
function openQR() {
    switchView('view-home'); // Keep home active underneath
    document.getElementById('view-qr').classList.add('active');
}

function closeQR() {
    document.getElementById('view-qr').classList.remove('active');
    switchView('view-home');
}

// Gosuslugi 
function openGosUslugi() {
    switchView('view-gosuslugi');
    
    // Show splash screen briefly
    const splash = document.getElementById('gos-splash');
    splash.style.display = 'flex';
    setTimeout(() => {
        splash.style.display = 'none';
    }, 1500);
}

function goBackHome() {
    switchView('view-home');
}

// ID Card (Udo)
function openUdo() {
    switchView('view-udo');
    
    // Read parameters from URL (generated by generator.html)
    const urlParams = new URLSearchParams(window.location.search);
    
    // Fill data if exists
    if (urlParams.has('surname') && urlParams.has('name')) {
        const fullName = `${urlParams.get('surname')} ${urlParams.get('name')} ${urlParams.get('patronymic') || ''}`;
        document.getElementById('udo-fio').textContent = fullName.trim();
        
        // Split IIN logic if needed, but here we just display it
        if (urlParams.has('iin')) {
            document.getElementById('udo-iin').textContent = urlParams.get('iin');
            
            // Try to extract date of birth from IIN (YYMMDD)
            const iin = urlParams.get('iin');
            if (iin && iin.length === 12) {
                const year = parseInt(iin.substring(0, 2));
                const month = iin.substring(2, 4);
                const day = iin.substring(4, 6);
                // Assume 19xx for year > 25, otherwise 20xx
                const fullYear = year > 25 ? `19${year}` : `20${year}`;
                document.getElementById('udo-dob').textContent = `${day}.${month}.${fullYear}`;
            }
        }
    }
}

function closeUdo() {
    switchView('view-gosuslugi');
}

function switchUdoTab(tab) {
    document.querySelectorAll('.udo-tab').forEach(el => el.classList.remove('active'));
    
    if (tab === 'doc') {
        document.getElementById('tab-doc-btn').classList.add('active');
        document.getElementById('tab-doc-content').style.display = 'block';
        document.getElementById('tab-rekv-content').style.display = 'none';
    } else {
        document.getElementById('tab-rekv-btn').classList.add('active');
        document.getElementById('tab-doc-content').style.display = 'none';
        document.getElementById('tab-rekv-content').style.display = 'flex';
    }
}

// Bottom nav event listeners
document.addEventListener('DOMContentLoaded', () => {
    document.getElementById('nav-home').addEventListener('click', () => switchView('view-home'));
    document.getElementById('nav-qr').addEventListener('click', openQR);
    document.getElementById('nav-messages').addEventListener('click', () => switchView('view-messages'));
    document.getElementById('nav-services').addEventListener('click', () => switchView('view-services'));
});
